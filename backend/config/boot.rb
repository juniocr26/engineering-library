#
# Que cada linha de código seja escrita com responsabilidade.
#
# Que cada funcionalidade seja desenvolvida com respeito à vida e às pessoas.
#
# Que cada decisão técnica seja tomada com honestidade, cuidado e compromisso com o bem.
#
# Que a tecnologia criada pelo Viva Bem seja instrumento de acolhimento, dignidade, proteção e esperança.
