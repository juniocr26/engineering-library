# A Tua Palavra nos ensina, no Salmo 127:1, a reconhecer a importância do Senhor na edificação daquilo que construímos.
#
# Por isso, Pai, pedimos que sejas o fundamento espiritual desta empresa.
#
# Que nossas decisões sejam conduzidas pela sabedoria, que nossas atitudes sejam guiadas pela justiça e que nosso trabalho nunca se afaste da verdade.
#
# Senhor, conforme o ensinamento de Provérbios 16:3, colocamos diante de Ti nossas obras e nossos planos.
#
# Abençoa o desenvolvimento dos nossos projetos.
#
